 assert.equal((await rpc('aria_quick_fail',job.id,job.lease_token,'late failure',60)).ok,false);
 job=replacement;
 assert.equal((await rpc('aria_quick_finish',job.id,job.lease_token,fallback,'Test.md',content,.95)).ok,true);
