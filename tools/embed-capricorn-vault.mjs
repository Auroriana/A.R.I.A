import {writeFile,rename} from 'node:fs/promises';
import {records} from '../web/lib/personality-data.js';
import {vectorIndex} from '../web/lib/personality-vectors.js';
import {embed} from '../web/lib/providers.js';
import {PERSONALITY_EMBEDDING,documentInput,hashText,normalizeVector} from '../web/lib/personality-embedding.js';

if(!process.env.GEMINI_API_KEY||process.env.GEMINI_FREE_TIER_CONFIRMED!=='true')throw new Error('Configure GEMINI_API_KEY and confirm GEMINI_FREE_TIER_CONFIRMED before indexing.');
const compatible=Object.entries(PERSONALITY_EMBEDDING).every(([k,v])=>vectorIndex[k]===v);
const previous=new Map((compatible?vectorIndex.entries:[]).map(e=>[e.id,e]));
const entries=[];let generated=0,reused=0;
const target=new URL('../web/lib/personality-vectors.js',import.meta.url),temp=new URL('../web/lib/personality-vectors.js.tmp',import.meta.url);
async function save(){await writeFile(temp,'// Generated by tools/embed-capricorn-vault.mjs. Never contains credentials.\nexport const vectorIndex = '+JSON.stringify({...PERSONALITY_EMBEDDING,entries})+';\n');await rename(temp,target);}
for(const record of records){
 const input=documentInput(record),inputHash=hashText(input),old=previous.get(record.id);
 let values;
 if(old?.contentHash===record.contentHash&&old.inputHash===inputHash){try{values=normalizeVector(old.values);}catch{}}
 if(values)reused++;
 else{
  // Bounded sequential requests; provider errors stop rather than retrying indefinitely.
  if(generated)await new Promise(resolve=>setTimeout(resolve,2200));
  values=normalizeVector(await embed(input));generated++;
 }
 entries.push({id:record.id,contentHash:record.contentHash,inputHash,values});
 // Checkpoint successful work, retaining compatible remaining records for resumability.
 const done=new Set(entries.map(e=>e.id));
 const current=[...entries];
 for(const r of records)if(!done.has(r.id)){const e=previous.get(r.id);if(e?.contentHash===r.contentHash&&e.inputHash===hashText(documentInput(r)))entries.push(e);}
 await save();entries.splice(0,entries.length,...current);
 console.log(`Indexed ${entries.length}/${records.length}; generated ${generated}, reused ${reused}.`);
}
await save();console.log('Personality semantic index is complete.');
